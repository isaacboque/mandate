import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { runAll, toDetailMarkdown, toMarkdown } from "../src/eval/run.js";

const results = await runAll();
const md = toMarkdown(results);
mkdirSync("eval", { recursive: true });
writeFileSync(
  "eval/RESULTS.md",
  `# Evaluation results\n\nGenerated by \`npm run eval\`: ${results.length} deterministic scenarios on the fixture catalog, a simulated clock and mock payments. ` +
    `A "fooled" scripted model proposes carts the mandate forbids; an independent oracle (it never calls the guardrail code) checks every captured payment against the mandate it was made under.\n\n${md}\n## Every scenario\n\n${toDetailMarkdown(results)}`,
);
const readme = readFileSync("README.md", "utf8");
const block = `<!-- eval:start -->\n${md}<!-- eval:end -->`;
writeFileSync("README.md", readme.includes("<!-- eval:start -->") ? readme.replace(/<!-- eval:start -->[\s\S]*<!-- eval:end -->/, block) : `${readme}\n## Evaluation\n\n${block}\n`);
console.log(md);
const bad = results.filter((r) => !r.pass || !r.noSpendOutsideMandate);
if (bad.length) {
  for (const r of bad) console.error(`FAIL ${r.id} ${r.title}${r.error ? ` (${r.error})` : ""}${r.violations.length ? ` violations: ${r.violations.join("; ")}` : ""}`);
  process.exit(1);
}
